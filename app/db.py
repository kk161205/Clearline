# Every table the app owns, parents before children (the copy tool keeps this order).
TABLES = ("events", "processed_webhooks", "buyer_summaries", "ai_state", "app_settings", "users",
          "sessions", "api_keys", "insights_layouts", "agent_calls")
# Tables whose id comes from the database (identity on Postgres): the copy resets their counters.
IDENTITY_TABLES = ("events", "users", "api_keys", "agent_calls")


def is_postgres(target: str) -> bool:
    return urlsplit(str(target)).scheme in POSTGRES_SCHEMES


def postgres_ddl(sql: str) -> str:
    """The SQLite schema in Postgres terms: identity ids and 8-byte floats (epoch seconds
    need more precision than Postgres's 4-byte REAL)."""
    sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)


def _dict_row(cursor, row):
    return {d[0]: v for d, v in zip(cursor.description, row)}


class Connection:
    """One transaction. execute() takes `?` placeholders on both databases."""

    def __init__(self, raw, postgres: bool):
        self.raw, self.postgres = raw, postgres

    def execute(self, sql: str, params=()):
        if self.postgres:
            return self.raw.execute(sql.replace("?", "%s"), tuple(params) if params else None)
        return self.raw.execute(sql, tuple(params))

    def executemany(self, sql: str, rows) -> None:
        if self.postgres:
            with self.raw.cursor() as cur:
                cur.executemany(sql.replace("?", "%s"), rows)
        else:
            self.raw.executemany(sql, rows)


_pools: dict[str, object] = {}
_migrated: dict[str, int] = {}  # target -> schema version reached in this process
_pools_lock = threading.Lock()
_last_used: "weakref.WeakKeyDictionary" = weakref.WeakKeyDictionary()
CHECK_AFTER_IDLE = 30  # seconds; a busy connection skips the extra round trip


def _check(conn) -> None:
    """Before handing out a connection that sat idle: one empty query, so a connection the
    server closed (Neon autosuspend, a restart) is discarded and replaced."""
    if time.monotonic() - _last_used.get(conn, 0) > CHECK_AFTER_IDLE:
        from psycopg_pool import ConnectionPool

        ConnectionPool.check_connection(conn)


def _returned(conn) -> None:
    _last_used[conn] = time.monotonic()


def _pool(url: str):
    """One pool per URL for the whole process (the app, the CLI and tests share it)."""
    with _pools_lock:
        pool = _pools.get(url)
        if pool is None:
            from psycopg.rows import dict_row
            from psycopg_pool import ConnectionPool

            pool = ConnectionPool(
                url, min_size=1, max_size=5, open=True, name="clearline",
                check=_check, reset=_returned, max_idle=240, reconnect_timeout=60, timeout=20,
                # prepare_threshold=None: no server-side prepared statements, which a
                # transaction-mode pooler (Neon's -pooler endpoint) can't keep per client.
                kwargs={"row_factory": dict_row, "prepare_threshold": None, "connect_timeout": 15,
                        "autocommit": True})
            _pools[url] = pool
    return pool


def quiet_driver_logs() -> None:
    """For command-line tools: the driver's own warnings can name the database host."""
    for name in ("psycopg", "psycopg.pool"):
        logger = logging.getLogger(name)
        logger.addHandler(logging.NullHandler())
        logger.propagate = False


def close_pool(url: str) -> None:
    """Close and forget the pool for one URL (tests, after dropping their schema)."""
    _migrated.pop(url, None)
    with _pools_lock:
        pool = _pools.pop(url, None)
    if pool is not None:
        pool.close()


@atexit.register
def _close_pools() -> None:
    for pool in list(_pools.values()):
        pool.close()
    _pools.clear()


class Database:
    def __init__(self, target: str):
        self.target = str(target)
        self.postgres = is_postgres(self.target)

    @contextmanager
    def connect(self):
        """For a single statement (or reads that don't need to agree with each other)."""
        if self.postgres:
            with _pool(self.target).connection() as raw:  # autocommit
                yield Connection(raw, True)
            return
        with self._sqlite() as conn:
            yield conn

    @contextmanager
    def transaction(self):
        """Several statements, all or nothing."""
        if self.postgres:
            with _pool(self.target).connection() as raw, raw.transaction():
                yield Connection(raw, True)
            return
        with self._sqlite() as conn:
            yield conn

    @contextmanager
    def _sqlite(self):
        raw = sqlite3.connect(self.target)
        raw.row_factory = _dict_row
        try:
            with raw:  # commits on success, rolls back on error
                yield Connection(raw, False)
        finally:
            raw.close()

    # ---- dialect helpers -----------------------------------------------------------

    def json_text(self, column: str, field: str) -> str:
        """SQL for one top-level JSON field of a TEXT column, as text."""
        assert re.fullmatch(r"\w+", column) and re.fullmatch(r"\w+", field)
        if self.postgres:
            return f"(({column})::jsonb ->> '{field}')"
        return f"json_extract({column}, '$.{field}')"

    def group_concat(self, column: str, order_by: str) -> str:
        assert re.fullmatch(r"\w+", column) and re.fullmatch(r"\w+", order_by)
        if self.postgres:
            return f"string_agg({column}, ',' ORDER BY {order_by})"
        return f"GROUP_CONCAT({column})"

    # ---- schema ----------------------------------------------------------------------

    def migrate(self) -> int:
        """Bring the schema up to date; returns the version. Safe to run any number of times
        and from several processes at once. Postgres: once per database per process (a SQLite
        file is local and cheap to check, and may be deleted and recreated at the same path)."""
        if self.target in _migrated:
            return _migrated[self.target]
        with self.transaction() as conn:
            if self.postgres:
                conn.execute(f"SELECT pg_advisory_xact_lock({MIGRATION_LOCK})")
            conn.execute("CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)")
            row = conn.execute("SELECT MAX(version) AS v FROM schema_version").fetchone()
            current = row["v"] or 0
            for version, sql in MIGRATIONS:
                if version <= current:
                    continue
                if self.postgres:  # the whole script in one round trip (no parameters)
                    conn.execute(postgres_ddl(sql))
                else:
                    for statement in filter(str.strip, sql.split(";")):
                        conn.execute(statement)
                conn.execute("INSERT INTO schema_version (version) VALUES (?)", (version,))
                current = version
        if self.postgres:
            _migrated[self.target] = current
        return current

    def ping(self) -> None:
        """A cheap round trip; raises if the database can't be reached."""
        with self.connect() as conn:
            conn.execute("SELECT 1").fetchone()

    def table_exists(self, table: str) -> bool:
        with self.connect() as conn:
            if self.postgres:
                row = conn.execute("SELECT to_regclass(?) AS t", (table,)).fetchone()
                return row["t"] is not None
            row = conn.execute("SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?",
                               (table,)).fetchone()
            return row is not None

    def count(self, table: str) -> int:
        assert table in TABLES or table == "schema_version", table
        with self.connect() as conn:
            return conn.execute(f"SELECT COUNT(*) AS n FROM {table}").fetchone()["n"]
